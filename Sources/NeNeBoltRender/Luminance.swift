/// 製品のコードで浮動小数点の `pow` を使わない（libm に頼らない・ADR 0001 の X-i）ため、sRGB の 256 段を線形に直した値を表で持つ。
/// 表は開発時に `((c + 0.055) / 1.055)^2.4` から作り、テストが浮動小数点の計算と突き合わせる。
enum Luminance {
    /// 色の相対輝度（0〜10000）。
    static func of(_ color: Rgb) -> Int {
        (2126 * linear[Int(color.red)] + 7152 * linear[Int(color.green)] + 722 * linear[Int(color.blue)]) / 10_000
    }

    /// 2 色のコントラスト比が `ratio`（整数）以上か。比は（明るい方 ＋ 0.05）÷（暗い方 ＋ 0.05）。
    static func contrasts(_ first: Rgb, _ second: Rgb, atLeast ratio: Int) -> Bool {
        let (a, b) = (of(first), of(second))
        return max(a, b) + 500 >= ratio * (min(a, b) + 500)
    }

